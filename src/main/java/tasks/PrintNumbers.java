package tasks;

import java.util.Scanner;

public class PrintNumbers {
    public static void main(String[] args) {
        // Print numbers from 1 to 10 using for loop
        System.out.print("Numbers from 1 to 10 : ");
        for (int i = 1; i <= 10; i++) {
            System.out.print(i + " ");
        }
    }
}
